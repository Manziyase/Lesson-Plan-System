export const LANG_NAMES: Record<string, string> = { en: "English", fr: "Français", rw: "Kinyarwanda" };
export const SUPPORTED_LANGS = ["en", "fr", "rw"] as const;
export type LangCode = (typeof SUPPORTED_LANGS)[number];

export function isSupportedLang(code: unknown): code is LangCode {
  return typeof code === "string" && (SUPPORTED_LANGS as readonly string[]).includes(code);
}

export function tr(lang: string, key: string, vars?: Record<string, string | number>): string {
  let s = (I18N[lang] && I18N[lang][key]) || key;
  if (vars) {
    for (const k of Object.keys(vars)) s = s.split("{" + k + "}").join(String(vars[k]));
  }
  return s;
}

export function localeFor(lang: string): string {
  return lang === "rw" ? "rw-RW" : lang === "fr" ? "fr-FR" : "en-GB";
}

export function langName(code: string): string {
  return LANG_NAMES[code] || code;
}
